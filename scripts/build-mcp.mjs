import { build } from "esbuild";
import { readFile, writeFile, readdir } from "node:fs/promises";
import { resolve, relative, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../", import.meta.url));
const result = await build({
  absWorkingDir: root,
  stdin: {
    contents: [
      'export { McpServer } from "@modelcontextprotocol/sdk/server/mcp.js";',
      'export { StdioServerTransport } from "@modelcontextprotocol/sdk/server/stdio.js";',
      'export { z } from "zod/v4";',
    ].join("\n"),
    resolveDir: root,
  },
  platform: "node",
  target: "node22.12",
  format: "cjs",
  bundle: true,
  minify: true,
  legalComments: "eof",
  metafile: true,
  write: false,
  banner: { js: "// Generated by npm run build:mcp. See NOTICES.txt for dependency licenses." },
});
const licenses = new Map();
for (const input of Object.keys(result.metafile.inputs)) {
  if (!input.includes("node_modules/")) continue;
  // Resolve the dependency package boundary even for nested dependencies.
  const leaf = input.slice(input.lastIndexOf("node_modules/") + "node_modules/".length);
  const name = leaf.split("/").slice(0, leaf.startsWith("@") ? 2 : 1).join("/");
  const folder = resolve(root, input.slice(0, input.length - leaf.length), name);
  if (licenses.has(folder)) continue;
  const info = JSON.parse(await readFile(join(folder, "package.json"), "utf8"));
  const filenames = (await readdir(folder)).filter(f => /^(licen[cs]e|copying|notice)(\..+)?$/i.test(f)).sort();
  if (!filenames.length) throw new Error("Missing license text for " + name);
  const text = await Promise.all(filenames.map(f => readFile(join(folder, f), "utf8")));
  licenses.set(folder, [info.name + "@" + info.version, ...text].join("\n\n"));
}
const notices = Array.from(licenses.values()).sort().join("\n\n-----\n\n");
const files = { "sdk.cjs": result.outputFiles[0].text, "NOTICES.txt": notices.trimEnd() + "\n" };
for (const [name, content] of Object.entries(files)) {
  const path = resolve(root, "mcp/vendor", name);
  if (process.argv.includes("--check")) {
    if (await readFile(path, "utf8") !== content) throw new Error(relative(root, path) + " is stale. Run npm run build:mcp.");
  } else {
    await writeFile(path, content);
  }
}
